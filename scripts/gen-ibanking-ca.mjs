// One-off generator: rebuilds lib/ibankingCaChain.ts from gs-intermediate.pem
// (downloaded from the bank cert's AIA URI). Run: node scripts/gen-ibanking-ca.mjs
import fs from "node:fs"

const pem = fs.readFileSync("gs-intermediate.pem", "utf8").trim()

const content = `/**
 * TLS chain helper for the iBanking proxy.
 *
 * The somiti's bank (corporatepay.mblbd.com — Mercantile Bank PLC) serves an
 * INCOMPLETE certificate chain: only the leaf certificate, without the
 * issuing intermediate. Browsers and Windows schannel complete the chain
 * automatically via AIA fetching, but Node's OpenSSL refuses with
 * UNABLE_TO_VERIFY_LEAF_SIGNATURE.
 *
 * This file bundles the missing intermediate (downloaded from the leaf's
 * AIA "CA Issuers" URI) so /api/ibanking-proxy can VERIFY — not bypass —
 * the bank's TLS certificate. Generated by scripts/gen-ibanking-ca.mjs.
 *
 * Valid until: 2027-07-16. If the bank rotates its certificate and the
 * proxy starts failing TLS again, re-download the intermediate and
 * re-run the generator:
 *   curl -s "http://secure.globalsign.com/cacert/gsgccr3evtlsca2025.crt" -o gs.der
 *   openssl x509 -inform DER -in gs.der -out gs-intermediate.pem
 *   node scripts/gen-ibanking-ca.mjs
 */
import tls from "node:tls"

export const IBANKING_BANK_INTERMEDIATE_PEM = \`${pem}\`

/**
 * Node's \`ca\` tls option REPLACES the default root store, so the full set —
 * built-in Mozilla roots plus the bank's intermediate — is required to keep
 * verifying the chain end-to-end (verification is never disabled).
 */
export const IBANKING_CA_CHAIN: string[] = [
  ...tls.rootCertificates,
  IBANKING_BANK_INTERMEDIATE_PEM,
]
`

fs.writeFileSync("lib/ibankingCaChain.ts", content)

// Verify the round-trip.
const written = fs.readFileSync("lib/ibankingCaChain.ts", "utf8")
const m = written.match(/-----BEGIN CERTIFICATE-----([\s\S]*?)-----END CERTIFICATE-----/)
const embedded = `-----BEGIN CERTIFICATE-----${m[1]}-----END CERTIFICATE-----`.trim()
console.log("round-trip match:", embedded === pem)
